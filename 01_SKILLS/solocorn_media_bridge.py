def run_local_omlx_inference(prompt, system_instruction, model="mlx-community/Qwen2.5-Coder-7B-Instruct-4bit"):
    """
    Direct, native endpoint query routing straight to the local MLX engine.
    """
    import urllib.request
    import json  # <-- ENSURE THIS IS EXPLICITLY HERE

    # Use the official OpenAI-compatible endpoint route provided by mlx_lm.server
    url = "http://127.0.0.1:8000/v1/chat/completions"
    headers = {"Content-Type": "application/json"}
    
    data = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_instruction},
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.1
    }

    req = urllib.request.Request(url, data=json.dumps(data).encode('utf-8'), headers=headers)
    try:
        with urllib.request.urlopen(req) as response:
            res = json.loads(response.read().decode('utf-8'))
            return res['choices'][0]['message']['content']
    except Exception as e:
        return f"ERROR: Direct local connection to native oMLX server failed. Details: {str(e)}"

