def generate_qa_verdict(task_id, task_description, developer_agent, qa_agent,
                        attempt, verdict, issues=None, evidence_screenshots=None):
    """Generates a QA PASS or FAIL verdict document for the Solocorn pipeline."""
    timestamp = datetime.now().strftime("%Y-%m-%dT%H:%M:%SZ")
    status_icon = "PASS" if verdict == "PASS" else "FAIL"

    doc_lines = [
        f"# Solocorn QA Verdict: {status_icon}",
        "",
        "## Task",
        f"| **Task ID** | {task_id} |",
        f"| **Task Description** | {task_description} |",
        f"| **Developer Agent** | {developer_agent} |",
        f"| **QA Agent** | {qa_agent} |",
        f"| **Attempt** | {attempt} of 3 |",
        f"| **Timestamp** | {timestamp} |",
        "",
        f"## Verdict: {status_icon}",
        ""
    ]

    if verdict == "PASS":
        if evidence_screenshots:
            doc_lines.append("## Evidence")
            for shot in evidence_screenshots:
                doc_lines.append(f"- {shot}")
        doc_lines.append("\n## Next Action")
        doc_lines.append(f"-> {developer_agent}: Mark task complete, advance to next task")
    else:
        doc_lines.append("## Issues Found")
        if issues:
            for i, issue in enumerate(issues, 1):
                doc_lines.append(f"\n### Issue {i}: {issue.get('category', 'General')} - {issue.get('severity', 'Medium')}")
                doc_lines.append(f"**Description**: {issue.get('description', '')}")
                doc_lines.append(f"**Fix instruction**: {issue.get('fix', '')}")
        doc_lines.append("\n## Retry Instructions")
        doc_lines.append(f"**For {developer_agent}**:")
        doc_lines.append("1. Fix ONLY the issues listed above")
        doc_lines.append("2. Do NOT introduce new features or changes")
        doc_lines.append("3. Re-submit for QA when all issues are addressed")
        doc_lines.append(f"4. This is attempt {attempt} of 3 maximum")
        if attempt >= 3:
            doc_lines.append("\n**ESCALATION**: Task exceeds 3 retry attempts. Escalate to Studio Producer.")

    doc_content = "\n".join(doc_lines)
    verdict_filename = f"qa_verdict_{task_id.replace(' ', '_').lower()}_{status_icon.lower()}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
    verdict_path = HANDOFF_DIR / "projects" / verdict_filename
    verdict_path.parent.mkdir(parents=True, exist_ok=True)

    with open(verdict_path, 'w', encoding='utf-8') as f:
        f.write(doc_content)

    print(f"[+] QA Verdict document generated: {verdict_path}")
    return str(verdict_path)


