def synthesize_voiceover(text_prompt: str, output_wav_path: str):
    """
    Synthesizes premium course lectures using high-definition macOS system voices.
    Outputs uncompressed broadcast-compliant PCM linear WAV files cleanly.
    """
    import subprocess
    from pathlib import Path
    
    target_path = Path(output_wav_path)
    target_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Temporary layout file mapping required for native processing paths
    temp_aiff = target_path.with_suffix(".aiff")
    
    print(f"🎙️ Rendering premium narration channel via Ava (Premium HQ Model)...")
    
    # Call the macOS high-fidelity engine layer directly
    subprocess.run(["say", "-v", "Ava", text_prompt, "-o", str(temp_aiff)], check=True)
    
    # Transcode the file instantly into clean, uncompressed linear WAV layout parameters via ffmpeg
    ffmpeg_cmd = [
        "ffmpeg", "-y", "-i", str(temp_aiff),
        "-acodec", "pcm_s16le", "-ar", "44100", "-ac", "1",
        str(target_path)
    ]
    subprocess.run(ffmpeg_cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
    
    # Clean up temporary structural file blocks safely
    if temp_aiff.exists():
        temp_aiff.unlink()
        
    print(f"📢 Narration rendering complete: Saved to {target_path}")
    return target_path




