def trigger_headless_3dsmax_render(
    scene_file: Path,
    output_image: Path,
    renderer: str = "arnold",
    frame_range: tuple[int, int] = (1, 1),
    render_preset: str | None = None,
    width: int = 1920,
    height: int = 1080,
    additional_args: list[str] | None = None,
) -> dict[str, Any]:
    """Launch a headless 3ds Max command-line render layer."""
    system = platform.system()

    if system == "Windows":
        program_files = os.environ.get("ProgramFiles", r"C:\Program Files")
        maxcmd_candidates = [
            Path(program_files) / "Autodesk" / "3ds Max 2025" / "3dsmaxcmd.exe",
            Path(program_files) / "Autodesk" / "3ds Max 2024" / "3dsmaxcmd.exe",
            Path(program_files) / "Autodesk" / "3ds Max 2023" / "3dsmaxcmd.exe",
        ]
    elif system == "Darwin":
        maxcmd_candidates = [
            Path("/Applications/Autodesk/3ds Max 2025/3dsmaxcmd.exe"),
            Path.home() / ".wine" / "drive_c" / "Program Files" / "Autodesk" / "3ds Max 2025" / "3dsmaxcmd.exe",
        ]
    else:
        maxcmd_candidates = [
            Path("/usr/autodesk/3dsmax/3dsmaxcmd"),
            Path("/opt/autodesk/3dsmax/3dsmaxcmd"),
        ]

    maxcmd = None
    for candidate in maxcmd_candidates:
        if candidate.exists():
            maxcmd = candidate
            break

    if maxcmd is None:
        return {
            "ok": False,
            "stdout": "",
            "stderr": f"3ds Max command-line executable not found. Searched: {[str(c) for c in maxcmd_candidates]}",
        }

    cmd = [
        str(maxcmd), "-v", "5", "-rfw", "0",
        "-o", str(output_image), "-w", str(width), "-h", str(height),
        "-s", str(frame_range[0]), "-e", str(frame_range[1]), "-r", renderer
    ]

    if render_preset is not None:
        cmd += ["-preset", str(render_preset)]
    if additional_args:
        cmd += additional_args
    cmd += [str(scene_file)]

    output_image.parent.mkdir(parents=True, exist_ok=True)

    env_override: dict[str, str] = {
        "SOLOCORN_RENDER_CONTEXT": "headless_3dsmax",
        "SOLOCORN_SCENE": str(scene_file),
    }

    result = _run(cmd, env=env_override)
    return {"ok": result.returncode == 0, "stdout": result.stdout, "stderr": result.stderr}


