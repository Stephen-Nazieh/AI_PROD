def _shell_quote(arg: str) -> str:
    """Cross-platform safe shell quoting."""
    if platform.system() == "Windows":
        return subprocess.list2cmdline([arg])
    return shlex.quote(arg)

def _run(cmd: list[str], cwd: Path | None = None, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    """Execute a subprocess and return its CompletedProcess handle."""
    merged_env = {**os.environ, **(env or {})}
    return subprocess.run(cmd, capture_output=True, text=True, cwd=cwd, env=merged_env, check=False)

