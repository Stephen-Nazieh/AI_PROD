def generate_fcpxml_timeline(track_assets: list, output_xml_path: str):
    """
    Programmatically builds a multi-track Final Cut Pro X (FCPXML v1.9) timeline.
    Stacks audio voiceover tracks directly underneath video asset clips as synchronized multi-channel layouts.
    """
    from pathlib import Path
    xml_path = Path(output_xml_path)
    xml_path.parent.mkdir(parents=True, exist_ok=True)
    
    xml_output = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE fcpxml>',
        '<fcpxml version="1.9">',
        '  <resources>',
        '    <format id="r1" name="FFVideoFormat1080p24" frameDuration="100/2400s"/>',
    ]
    
    # 1. Map assets out into distinct dictionary structures grouped by scene number
    scenes_data = {}
    asset_id_map = {}
    
    for i, asset in enumerate(track_assets, start=1):
        asset_path = Path(asset).resolve()
        file_url = asset_path.as_uri()
        asset_id = f"r{i+1}"
        asset_id_map[str(asset_path)] = asset_id
        
        # Parse out scene index sequence from file names (e.g., scene_1_voice -> 1)
        try:
            scene_num = int(asset_path.stem.split('_')[1])
        except Exception:
            scene_num = i
            
        if scene_num not in scenes_data:
            scenes_data[scene_num] = {"video": None, "audio": None}
            
        is_audio = asset_path.suffix.lower() == '.wav'
        if is_audio:
            scenes_data[scene_num]["audio"] = asset_path
        else:
            scenes_data[scene_num]["video"] = asset_path
            
        duration_frames, fcp_str = snap_seconds_to_frames(get_wav_duration(str(asset_path)) if is_audio else 6.0, fps=24)
        scenes_data[scene_num][f"{'audio' if is_audio else 'video'}_duration_str"] = fcp_str
        scenes_data[scene_num][f"{'audio' if is_audio else 'video'}_frames"] = duration_frames
        
        xml_output.append(f'    <asset id="{asset_id}" name="{asset_path.name}" start="0s" duration="{fcp_str}" hasVideo="{"0" if is_audio else "1"}" hasAudio="1" format="r1">')
        xml_output.append(f'      <media-rep kind="original-media" src="{file_url}"/>')
        xml_output.append('    </asset>')
        
    # Calculate the total sequence length using the combined sum of video scenes
    total_sequence_frames = 0
    for s_idx in sorted(scenes_data.keys()):
        v_path = scenes_data[s_idx]["video"]
        a_path = scenes_data[s_idx]["audio"]
        # Use audio duration as master anchor pacing length metric
        if a_path:
            total_sequence_frames += scenes_data[s_idx]["audio_frames"]
        elif v_path:
            total_sequence_frames += scenes_data[s_idx]["video_frames"]
            
    total_sequence_fcp_string = f"{total_sequence_frames * 100}/2400s"
    
    xml_output.extend([
        '  </resources>',
        '  <library>',
        '    <event name="Solocorn Automated Production">',
        '      <project name="Assembled_Lesson_Timeline">',
        f'        <sequence duration="{total_sequence_fcp_string}" format="r1" tcStart="0s">',
        '          <spine>'
    ])
    
    # 2. Second Pass: Assemble Stacked Clips End-to-End on the Timeline Spine
    current_frame_offset = 0
    for s_idx in sorted(scenes_data.keys()):
        video_path = scenes_data[s_idx]["video"]
        audio_path = scenes_data[s_idx]["audio"]
        
        if not video_path:
            continue
            
        # Match audio tracking lengths to ensure video tracks span perfectly
        audio_frames = scenes_data[s_idx]["audio_frames"] if audio_path else 144
        duration_str = scenes_data[s_idx]["audio_duration_str"] if audio_path else "14400/2400s"
        offset_str = f"{current_frame_offset * 100}/2400s"
        
        video_ref = asset_id_map[str(video_path)]
        
        xml_output.append(f'            <asset-clip name="{video_path.stem}" ref="{video_ref}" offset="{offset_str}" duration="{duration_str}" start="0s">')
        
        # 🔗 Nest the audio track inside the video asset block as a synchronized multi-channel sub-clip element
        if audio_path:
            audio_ref = asset_id_map[str(audio_path)]
            xml_output.append(f'              <asset-clip name="{audio_path.stem}" ref="{audio_ref}" offset="0s" duration="{duration_str}" start="0s" lane="-1"/>')
            
        xml_output.append('            </asset-clip>')
        current_frame_offset += audio_frames

    xml_output.extend([
        '          </spine>',
        '        </sequence>',
        '      </project>',
        '    </event>',
        '  </library>',
        '</fcpxml>'
    ])
    
    xml_path.write_text("\n".join(xml_output), encoding="utf-8")
    print(f"🎬 NLE COMPILATION COMPLETE: Multi-track stacked FCPXML saved to {xml_path}")
    return xml_path

